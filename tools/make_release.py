"""Build the archive that goes to Zenodo: paper02-conflict-fusion-v1.zip (+ MANIFEST.sha256).

    python tools/make_release.py            # writes release/ and prints what is inside

Included: code, tests, config, notes, aggregate results (json/md/png/pdf) and figures, plus the two
reproducibility SCRIPTS the paper's own text points readers to (paper/latex/make_paper_data.py,
make_stubs.py -- these turn results/*.json into the manuscript's numbers; they are code, not the paper).
Excluded on purpose: datasets and caches, fitted-model pickles, third-party checkpoints (code/), the Elsevier
template and reference PDFs (their own licences), logs, anything larger than MAX_MB, and -- deliberately, per
the author's instruction -- the manuscript itself: no main.tex, no sections/*.tex, no compiled PDF, no
cls/sty/bst typesetting files. This archive is code + data + pre-registrations for the "data availability"
citation, not a preprint of the paper.
"""
import hashlib
import zipfile
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
OUT = ROOT / "release"
MAX_MB = 25
INCLUDE_TOP = ["src", "tests", "configs", "notes", "tools", "PLAN.md", "README.md", "LICENSE",
               "CITATION.cff", "requirements.txt", ".zenodo.json",
               "paper/latex/make_paper_data.py", "paper/latex/make_stubs.py"]
INCLUDE_RESULTS = ["REPORT.md", "multiseed_exp2.json", "multiseed_exp2.md", "exp1_harm", "exp2_routing", "exp3_ablation",
                   "exp4_conformal", "exp5_cadc", "exp6_raf", "exp7_dropout", "exp8_qualitative", "figures", "r2", "r2d",
                   "truckscenes/r2", "truckscenes/r3", "truckscenes/r4", "truckscenes_dev/r3", "r3", "r4", "supplementary", "sim2real",
                   "ts_detector"] + [f"seed{i}/exp2_routing" for i in range(5)]
SKIP_PARTS = {"__pycache__", ".pytest_cache", "models", "models_cv", "models_r2", "models_noradar", "cache", "candidates"}
SKIP_SUFFIX = {".pkl", ".npz", ".aux", ".log", ".out", ".blg", ".bbl", ".toc", ".synctex.gz", ".pyc"}
SKIP_NAMES = {"autogen_stubs.tex"}  # regenerated by make_stubs.py


def files():
    for rel in INCLUDE_TOP:
        p = ROOT / rel
        yield from ([p] if p.is_file() else sorted(q for q in p.rglob("*") if q.is_file())) if p.exists() else []
    for rel in INCLUDE_RESULTS:
        p = ROOT / "results" / rel
        yield from ([p] if p.is_file() else sorted(q for q in p.rglob("*") if q.is_file())) if p.exists() else []


def keep(p):
    rel = p.relative_to(ROOT)
    return (not (set(rel.parts) & SKIP_PARTS) and p.suffix not in SKIP_SUFFIX and p.name not in SKIP_NAMES
            and "STALE" not in p.name and p.stat().st_size <= MAX_MB * 2 ** 20)


def main():
    OUT.mkdir(exist_ok=True)
    zpath = OUT / "paper02-conflict-fusion-v1.zip"
    chosen = [p for p in dict.fromkeys(files()) if keep(p)]
    lines = []
    with zipfile.ZipFile(zpath, "w", zipfile.ZIP_DEFLATED) as z:
        for p in chosen:
            rel = p.relative_to(ROOT).as_posix()
            z.write(p, f"paper02-conflict-fusion/{rel}")
            lines.append(f"{hashlib.sha256(p.read_bytes()).hexdigest()}  {rel}")
    (OUT / "MANIFEST.sha256").write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"{len(chosen)} files, {zpath.stat().st_size / 2 ** 20:.1f} MB -> {zpath}")


if __name__ == "__main__":
    main()
