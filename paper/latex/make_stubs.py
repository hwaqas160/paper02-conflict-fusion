"""Generate autogen_stubs.tex: \\providecommand fallbacks for every \\NumXxx macro referenced anywhere in
sections/*.tex, so the paper always compiles even before all results JSONs exist. autogen_numbers.tex
(from make_paper_data.py) uses \\renewcommand and overrides these once real data is available.

    python paper/latex/make_stubs.py
"""
import glob
import re
from pathlib import Path

HERE = Path(__file__).resolve().parent


def main():
    names = set()
    for f in glob.glob(str(HERE / "sections" / "*.tex")):
        names |= set(re.findall(r"\\(Num[A-Za-z0-9]+)", Path(f).read_text(encoding="utf-8")))
    lines = ["% AUTO-GENERATED by paper/latex/make_stubs.py.",
             "% Fallback stubs; each is overwritten by autogen_numbers.tex (\\DefNum, unconditional) once its",
             "% source JSON exists. Uses \\DefNum, defined in main.tex, not \\newcommand/\\providecommand,",
             "% so load order relative to autogen_numbers.tex only needs stubs first.", ""]
    for n in sorted(names):
        name = n[len("Num"):]  # \DefNum{X}{...} defines \NumX
        lines.append(f"\\DefNum{{{name}}}{{--}}")
    (HERE / "autogen_stubs.tex").write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"{len(names)} stubs written to {HERE / 'autogen_stubs.tex'}")


if __name__ == "__main__":
    main()
